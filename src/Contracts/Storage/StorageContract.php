<?php

declare(strict_types=1);

namespace Sahil\Contracts\Storage;

use Closure;
use Sahil\Storage\StoredFile;

/**
 * Storage manager contract.
 *
 * Provides a disk-oriented, high-level API over storage drivers. The
 * default disk serves unqualified calls; any disk can be addressed
 * explicitly. Remote backends are supported by registering a driver
 * factory through {@see extend()}.
 */
interface StorageContract
{
    /** Resolve a driver for the given disk (default disk when null). */
    public function disk(?string $name = null): StorageDriverContract;

    /** Register (or override) a driver factory for remote/custom backends. */
    public function extend(string $driver, Closure $factory): void;

    /**
     * Write (create or overwrite) a file on the given disk.
     *
     * @param string|resource $contents file contents or an open readable stream
     */
    public function put(string $path, $contents, ?string $disk = null): void;

    /** Read a file's contents as a string. */
    public function get(string $path, ?string $disk = null): string;

    /**
     * Open a readable stream to the file.
     *
     * @return resource
     */
    public function readStream(string $path, ?string $disk = null);

    /** Whether the path exists on the disk. */
    public function has(string $path, ?string $disk = null): bool;

    /** File size in bytes. */
    public function size(string $path, ?string $disk = null): int;

    /** Server-detected MIME type of the file. */
    public function mimeType(string $path, ?string $disk = null): string;

    /** Last modification time as a UNIX timestamp. */
    public function lastModified(string $path, ?string $disk = null): int;

    /** Delete a file; returns false when nothing existed. */
    public function delete(string $path, ?string $disk = null): bool;

    /** Copy a file within its disk. */
    public function copy(string $from, string $to, ?string $disk = null): void;

    /** Move a file within its disk. */
    public function move(string $from, string $to, ?string $disk = null): void;

    /** Create a directory (recursively when requested). */
    public function makeDirectory(string $path, bool $recursive = false, ?string $disk = null): void;

    /** Recursively delete a directory. */
    public function deleteDirectory(string $path, ?string $disk = null): void;

    /**
     * List the contents of a directory.
     *
     * @return list<array{path: string, type: 'file'|'dir', size: int, mime_type: string|null, last_modified: int|null}>
     */
    public function listContents(string $path = '', ?string $disk = null): array;

    /** Public URL for the path, or null when the disk is not public. */
    public function url(string $path, ?string $disk = null): ?string;

    /**
     * Accept and store an uploaded file.
     *
     * Client-supplied data (name, MIME type, extension, size) is never
     * trusted: type is detected server-side from the file content, the
     * stored name is generated by the framework, and the size is measured
     * from the actual upload stream. An extension that a web server could
     * execute (php, cgi, sh, ...) is always refused — there is no option to
     * enable it.
     *
     * @param array{
     *     max_size?: int,
     *     allowed_mimes?: list<string>,
     *     path?: string,
     * } $options
     */
    public function upload(string $inputName, array $options, ?string $disk = null): StoredFile;
}
