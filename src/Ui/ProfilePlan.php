<?php

declare(strict_types=1);

namespace Sahil\Ui;

/**
 * The files and manifest a profile would generate, before conflict checks.
 */
final class ProfilePlan
{
    /**
     * @param array<string, string> $files   project-relative path => content
     * @param array<string, mixed>  $package decoded package.json payload
     */
    private function __construct(
        public readonly Profile $profile,
        public readonly array $files,
        public readonly array $package,
    ) {
    }

    public static function build(Profile $profile, string $packageName = 'sahilphp-app'): self
    {
        $package = [
            'name' => $packageName,
            'private' => true,
            'scripts' => [
                'dev' => 'vite',
                'build' => 'vite build',
                'preview' => 'vite preview',
            ],
            'devDependencies' => $profile->dependencies(),
        ];

        ksort($package['devDependencies']);

        $files = [
            'package.json' => self::encodePackage($package),
            'vite.config.js' => self::viteConfig($profile),
        ];

        if ($profile === Profile::Tailwind || $profile === Profile::Both) {
            $files['resources/css/tailwind.css'] = self::tailwindCss();
        }

        if ($profile === Profile::Bootstrap || $profile === Profile::Both) {
            $files['resources/css/bootstrap.css'] = self::bootstrapCss();
            $files['resources/js/bootstrap.js'] = self::bootstrapJs();
        }

        if ($profile === Profile::None) {
            $files['resources/css/app.css'] = self::plainCss();
        }

        ksort($files);

        return new self($profile, $files, $package);
    }

    /**
     * @param array<string, mixed> $package
     */
    public static function encodePackage(array $package): string
    {
        $json = json_encode($package, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);

        if ($json === false) {
            throw new UiException('Unable to encode the generated package.json.');
        }

        return $json."\n";
    }

    private static function viteConfig(Profile $profile): string
    {
        $plugins = $profile->includesTailwind()
            ? "const tailwindcss = require('@tailwindcss/vite').default;\n"
            : '';

        $input = [];

        if ($profile === Profile::Tailwind || $profile === Profile::Both) {
            $input[] = "        tailwind: 'resources/css/tailwind.css',";
        }

        if ($profile === Profile::Bootstrap || $profile === Profile::Both) {
            $input[] = "        bootstrap: 'resources/js/bootstrap.js',";
        }

        if ($profile === Profile::None) {
            $input[] = "        app: 'resources/css/app.css',";
        }

        $inputBlock = implode("\n", $input);
        $pluginBlock = $profile->includesTailwind()
            ? '  plugins: [tailwindcss()],'."\n"
            : '';

        return <<<JS
            /**
             * Generated by `bin/sahil ui:install` — profile: {$profile->value}.
             *
             * Output names are deterministic because SahilPHP templates reference
             * stable asset paths. Run `bin/sahil ui:build --clean` to remove stale
             * outputs from a previous profile.
             */
            const { defineConfig } = require('vite');
            {$plugins}
            module.exports = defineConfig({
            {$pluginBlock}  publicDir: false,
              // Keep Vite's cache inside project storage instead of node_modules.
              cacheDir: 'storage/framework/vite',
              build: {
                outDir: 'public/build',
                // Multiple profiles may build into the same directory; `ui:build --clean`
                // owns removal instead of Vite emptying outputs it does not produce.
                emptyOutDir: false,
                rollupOptions: {
                  input: {
            {$inputBlock}
                  },
                  output: {
                    entryFileNames: 'assets/[name].js',
                    chunkFileNames: 'assets/[name].js',
                    assetFileNames: 'assets/[name][extname]',
                  },
                },
              },
              server: {
                host: '127.0.0.1',
                port: 5173,
              },
            });

            JS;
    }

    private static function tailwindCss(): string
    {
        return <<<'CSS'
            /* Generated by `bin/sahil ui:install` — Tailwind CSS v4. */
            @import "tailwindcss";

            /* Templates and application classes scanned for utility names. */
            @source "../../views/**/*.sahil.php";
            @source "../../resources/views/**/*.sahil.php";
            @source "../../app/**/*.php";
            @source "../../resources/css/**/*.css";

            /*
             * These fallbacks keep a freshly installed profile usable before the
             * optional theme layer is generated. Running `ui:theme` defines the
             * neutral --sahil-* variables, and the selectors below then use them.
             */
            @theme {
              --color-primary: var(--sahil-color-primary, oklch(0.55 0.22 264));
              --color-primary-foreground: var(--sahil-color-primary-foreground, oklch(0.98 0 0));
              --color-surface: var(--sahil-color-surface, oklch(0.99 0 0));
              --font-sans: var(--sahil-font-sans, ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif);
            }

            @layer base {
              body {
                background-color: var(--color-surface);
                color: var(--sahil-color-text, oklch(0.21 0.02 264));
                font-family: var(--font-sans);
                -webkit-font-smoothing: antialiased;
              }
            }

            CSS;
    }

    private static function bootstrapCss(): string
    {
        return <<<'CSS'
            /* Generated by `bin/sahil ui:install` — Bootstrap 5. */
            @import "bootstrap/dist/css/bootstrap.min.css";

            /*
             * Application overrides belong here. This file is imported after Bootstrap
             * by resources/js/bootstrap.js, so equal-specificity rules win.
             */
            :root {
              --sahil-primary: var(--sahil-color-primary, #0d6efd);
            }

            CSS;
    }

    private static function bootstrapJs(): string
    {
        return <<<'JS'
            /**
             * Generated by `bin/sahil ui:install` — Bootstrap 5 entry point.
             *
             * One ESM import registers every data-api plugin (dropdowns, tooltips,
             * toasts, modals, ...). Popper comes from Bootstrap's own dependency.
             */
            import '../css/bootstrap.css';
            import * as bootstrap from 'bootstrap';

            window.bootstrap = bootstrap;

            export default bootstrap;
            JS;
    }

