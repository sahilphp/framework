<?php

declare(strict_types=1);

namespace Sahil\Installer;

use FilesystemIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use Sahil\Encryption\KeyGenerator;
use Sahil\Ui\InstallOptions;
use Sahil\Ui\ProcessFailureException;
use Sahil\Ui\ProcessResult;
use Sahil\Ui\ProcessRunner;
use Sahil\Ui\Profile;
use Sahil\Ui\Toolchain;
use Sahil\Ui\ToolchainDetector;
use Sahil\Ui\UiInstaller;
use SplFileInfo;

/**
 * Creates a new SahilPHP application from the starter-kit.
 *
 * The installer copies only source files, applies exactly one UI profile
 * through the existing UiInstaller, installs the matching dependencies and
 * generates a local application key. It never fetches a template over the
 * network and never writes into an existing non-empty destination.
 */
final class ProjectInstaller
{
    public const MINIMUM_PHP_VERSION = '8.1.0';

    /**
     * Frontend files from earlier starter-kit generations. They are not part
     * of a selected profile and are removed from every generated project.
     *
     * @var list<string>
     */
    private const OBSOLETE_UI_FILES = [
        'postcss.config.cjs',
        'postcss.config.js',
        'postcss.config.mjs',
        'resources/css/app.css',
        'resources/css/bootstrap-overrides.css',
        'resources/js/bootstrap-sass.js',
        'resources/js/bootstrap-starter.js',
        'resources/sass/bootstrap.scss',
        'tailwind.config.cjs',
        'tailwind.config.js',
        'tailwind.config.mjs',
        'tailwind.config.ts',
        'vite.bootstrap.config.js',
    ];

    /**
     * @var list<string>
     */
    private const TAILWIND_ONLY_FILES = [
        'resources/css/tailwind.css',
    ];

    /**
     * @var list<string>
     */
    private const BOOTSTRAP_ONLY_FILES = [
        'resources/css/bootstrap.css',
        'resources/js/bootstrap.js',
    ];

    /**
     * Top-level paths that are machine-local or generated.
     *
     * @var list<string>
     */
    private const SKIP_TOP_LEVEL = [
        '.freebuff',
        '.git',
        '.idea',
        '.php-cs-fixer.cache',
        '.phpstan.cache',
        '.phpunit.cache',
        '.phpunit.result.cache',
        '.vscode',
        'composer.json.backup',
        'coverage',
        'dist',
        'node_modules',
        'stubs',
        'vendor',
    ];

    /**
     * JavaScript lock files. The generated package.json contains only the
     * selected profile, so a copied lock file would describe another set of
     * dependencies and must be regenerated by the package manager.
     *
     * @var list<string>
     */
    private const SKIP_JS_LOCKS = [
        'bun.lock',
        'bun.lockb',
        'npm-shrinkwrap.json',
        'package-lock.json',
        'pnpm-lock.yaml',
        'yarn.lock',
    ];

    public function __construct(
        private readonly ProcessRunner $runner = new ProcessRunner(),
        private readonly UiInstaller $uiInstaller = new UiInstaller(),
        private readonly ToolchainDetector $toolchainDetector = new ToolchainDetector(),
        private readonly ExecutableLocator $locator = new ExecutableLocator(),
    ) {
    }

    /**
     * @param (callable(string): void)|null $progress
     */
    public function install(ProjectOptions $options, ?callable $progress = null): ProjectReport
    {
        $this->assertPhpVersion();
        $this->assertProjectName($options->projectName);
        $this->assertSupportedProfile($options->ui);

        $source = $this->validateSource($options->sourcePath);
        $destination = $this->absolutePath($options->destination, $this->workingDirectory());

        $this->assertDestinationAvailable($destination, $source);

        [$composer, $toolchain] = $this->preflight($source, $options->installDependencies);

        $report = new ProjectReport(
            $options->projectName,
            $destination,
            $options->ui,
            $options->installDependencies,
        );

        $this->notify($progress, 'Creating project...');
        $this->createDestination($destination, $source);

        $this->notify($progress, 'Copying application files...');
        $report->filesCopied = $this->copyTree($source, $destination);
        $this->removeFiles($destination, self::OBSOLETE_UI_FILES, $report);

        $this->notify($progress, 'Generating the selected UI configuration...');
        $report->ui = $this->uiInstaller->install(
            $destination,
            $options->ui,
            new InstallOptions(overwrite: true, installDependencies: false),
        );

        // The source checkout ships a different UI manifest than the selected
        // profile, so --overwrite backs up the old package.json/vite.config.js.
        // Those backups belong to this one-shot generation step; keeping them
        // would leave the unselected framework's dependencies in the project.
        $this->removeInstallerBackups($destination);

        $this->removeFiles($destination, $this->unselectedUiFiles($options->ui), $report);

        if ($options->installDependencies) {
            $this->notify($progress, 'Installing PHP dependencies...');
            $report->composerInstall = $this->installComposerDependencies(
                $destination,
                $composer,
                $options->installDevDependencies,
            );

            $this->notify($progress, 'Installing selected UI dependencies...');
            $report->uiDependencyInstall = $this->installUiDependencies($destination, $toolchain);
        } else {
            $report->notes[] = 'dependency installation skipped (--no-install); run Composer and npm when ready';
        }

        $this->notify($progress, 'Generating application configuration...');
        $this->configureEnvironment($destination, $report);

        return $report;
    }

    private function assertPhpVersion(): void
    {
        if (version_compare(PHP_VERSION, self::MINIMUM_PHP_VERSION, '<')) {
            throw new InstallerException(sprintf(
                'SahilPHP requires PHP %s or newer; this PHP is %s. '
                .'Install a supported PHP version and re-run the installer.',
                self::MINIMUM_PHP_VERSION,
                PHP_VERSION,
            ));
        }
    }

    private function assertProjectName(string $name): void
    {
        $valid = preg_match('/^[A-Za-z0-9](?:[A-Za-z0-9._-]{0,99})$/D', $name) === 1;

        if (!$valid || str_ends_with($name, '.')) {
            throw new InstallerException(sprintf(
                'Invalid project name [%s]. Use 1-100 letters, digits, dots, underscores or '
                .'hyphens, starting with a letter or digit (for example: my-app).',
                $name,
            ));
        }
    }

    private function assertSupportedProfile(Profile $profile): void
    {
        if ($profile !== Profile::Tailwind && $profile !== Profile::Bootstrap) {
            throw new InstallerException(sprintf(
                'Choose exactly one UI framework: tailwind or bootstrap. [%s] is not supported by the installer.',
                $profile->value,
            ));
        }
    }

    private function validateSource(string $sourcePath): string
    {
        if (!is_dir($sourcePath)) {
            throw new InstallerException(sprintf('Starter-kit directory [%s] does not exist.', $sourcePath));
        }

        $resolved = realpath($sourcePath);

        if ($resolved === false) {
            throw new InstallerException(sprintf('Unable to resolve starter-kit directory [%s].', $sourcePath));
        }

        foreach (['composer.json', 'bin/sahil', 'bootstrap/app.php'] as $file) {
            if (!is_file($resolved.'/'.$file)) {
                throw new InstallerException(sprintf(
                    'Starter-kit directory [%s] is incomplete: missing %s.',
                    $resolved,
                    $file,
                ));
            }
        }

        if (!is_dir($resolved.'/app')) {
            throw new InstallerException(sprintf(
                'Starter-kit directory [%s] is incomplete: missing app/.',
                $resolved,
            ));
        }

        return $resolved;
    }

    private function assertDestinationAvailable(string $destination, string $source): void
    {
        if (preg_match('#^[A-Za-z]:[\\\\/]?$#', $destination) === 1 || $destination === DIRECTORY_SEPARATOR) {
            throw new InstallerException('Refusing to use a filesystem root as the project destination.');
        }

        if (is_link($destination)) {
            throw new InstallerException(sprintf(
                'Destination [%s] is a symbolic link. Choose a real directory instead.',
                $destination,
            ));
        }

        $this->assertOutsideSource($this->effectivePath($destination), $source);

        if (file_exists($destination)) {
            if (!is_dir($destination)) {
                throw new InstallerException(sprintf(
                    'Destination [%s] exists and is not a directory.',
                    $destination,
                ));
            }

            if (!$this->isEmptyDirectory($destination)) {
                throw new InstallerException(sprintf(
                    'Destination [%s] already exists and is not empty. '
                    .'Choose another destination; the installer never overwrites an existing project.',
                    $destination,
                ));
            }
        }
    }

    private function assertOutsideSource(string $destination, string $source): void
    {
        if ($destination === $source) {
            throw new InstallerException(sprintf(
                'Destination [%s] is the starter-kit source directory. '
                .'Choose a child directory or another location.',
                $destination,
            ));
        }
    }

    /**
     * @return array{0: string, 1: Toolchain}
     */
    private function preflight(string $source, bool $installDependencies): array
    {
        if (!$installDependencies) {
            return ['', new Toolchain()];
        }

        $composer = $this->locator->find('composer');

        if ($composer === null) {
            throw new InstallerException(
                "Composer was not found on PATH.\n"
                ."  - Install Composer 2.x (https://getcomposer.org/download/) and re-run the installer,\n"
                .'  - or pass --no-install to generate the project files without installing dependencies.',
            );
        }

        $toolchain = $this->toolchainDetector->detect($source);

        if (!$toolchain->isReady()) {
            throw new InstallerException(
                "Missing frontend prerequisites:\n  - "
                .implode("\n  - ", $toolchain->issues())
                ."\nPass --no-install to generate files without installing the selected UI dependencies.",
            );
        }

        return [$composer, $toolchain];
    }

    private function createDestination(string $destination, string $source): void
    {
        $parent = dirname($destination);

        if (!is_dir($parent) && !mkdir($parent, 0o775, true) && !is_dir($parent)) {
            throw new InstallerException(sprintf('Unable to create destination parent [%s].', $parent));
        }

        if (!is_dir($destination)) {
            if (!mkdir($destination, 0o775) && !is_dir($destination)) {
                throw new InstallerException(sprintf('Unable to create project directory [%s].', $destination));
            }
        }

        $resolved = realpath($destination);

        if ($resolved === false) {
            throw new InstallerException(sprintf('Unable to resolve project directory [%s].', $destination));
        }

        $this->assertOutsideSource($resolved, $source);

        if (!is_writable($resolved)) {
            throw new InstallerException(sprintf('Project directory [%s] is not writable.', $resolved));
        }
    }

    private function copyTree(string $source, string $destination): int
    {
        $copied = 0;
        $resolvedDestination = realpath($destination);
        $relativeDestination = null;

        if ($resolvedDestination !== false && str_starts_with($resolvedDestination, $source.DIRECTORY_SEPARATOR)) {
            $relativeDestination = str_replace('\\', '/', substr($resolvedDestination, strlen($source) + 1));
        }

        $items = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($source, FilesystemIterator::SKIP_DOTS),
            RecursiveIteratorIterator::SELF_FIRST,
        );

        /** @var SplFileInfo $item */
        foreach ($items as $item) {
            $path = $item->getPathname();
            $relative = str_replace('\\', '/', substr($path, strlen($source) + 1));

            if ($relative === '' || $this->shouldSkip($relative)) {
                continue;
            }

            if (
                $relativeDestination !== null
                && ($relative === $relativeDestination || str_starts_with($relative, $relativeDestination.'/'))
            ) {
                continue;
            }

            if ($item->isLink()) {
                continue;
            }

            $target = $destination.DIRECTORY_SEPARATOR.str_replace('/', DIRECTORY_SEPARATOR, $relative);

            if ($item->isDir()) {
                if (!is_dir($target) && !mkdir($target, 0o775) && !is_dir($target)) {
                    throw new InstallerException(sprintf('Unable to create directory [%s].', $target));
                }

                continue;
            }

            if (!is_file($path)) {
                continue;
            }

            $directory = dirname($target);

            if (!is_dir($directory) && !mkdir($directory, 0o775, true) && !is_dir($directory)) {
                throw new InstallerException(sprintf('Unable to create directory [%s].', $directory));
            }

            if (!copy($path, $target)) {
                throw new InstallerException(sprintf('Unable to copy [%s].', $relative));
            }

            $permissions = fileperms($path);

            if ($permissions !== false) {
                @chmod($target, $permissions & 0o777);
            }

            $copied++;
        }

        return $copied;
    }

    private function shouldSkip(string $relative): bool
    {
        $segments = explode('/', trim($relative, '/'));

        if (in_array('.git', $segments, true) || in_array('.DS_Store', $segments, true)) {
            return true;
        }

        $top = $segments[0];

        if (in_array($top, self::SKIP_TOP_LEVEL, true)) {
            return true;
        }

        if ($relative === '.env' || (str_starts_with($relative, '.env.') && $relative !== '.env.example')) {
            return true;
        }

        if (in_array($relative, self::SKIP_JS_LOCKS, true)) {
            return true;
        }

        if ($relative === 'public/hot' || $relative === 'public/build' || str_starts_with($relative, 'public/build/')) {
            return true;
        }

        if ($top === 'storage' && count($segments) > 1) {
            $basename = basename($relative);

            if ($basename !== '.gitkeep' && $relative !== 'storage/README.md') {
                return true;
            }
        }

        return false;
    }

    /**
     * @param list<string> $files
     */
    private function removeFiles(string $destination, array $files, ProjectReport $report): void
    {
        foreach ($files as $relative) {
            $path = $destination.DIRECTORY_SEPARATOR.str_replace('/', DIRECTORY_SEPARATOR, $relative);

            if (!is_file($path) && !is_link($path)) {
                continue;
            }

            if (!unlink($path)) {
                throw new InstallerException(sprintf('Unable to remove obsolete file [%s].', $relative));
            }

            $report->removed[] = $relative;
            $this->removeEmptyParent($destination, dirname($path));
        }
    }

    private function removeEmptyParent(string $destination, string $directory): void
    {
        while ($directory !== $destination && str_starts_with($directory, $destination.DIRECTORY_SEPARATOR)) {
            if (!@rmdir($directory)) {
                return;
            }

            $directory = dirname($directory);
        }
    }

    private function removeInstallerBackups(string $destination): void
    {
        $backups = $destination.'/storage/framework/ui-backups';

        if (!is_dir($backups)) {
            return;
        }

        $items = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($backups, FilesystemIterator::SKIP_DOTS),
            RecursiveIteratorIterator::CHILD_FIRST,
        );

        /** @var SplFileInfo $item */
        foreach ($items as $item) {
            $path = $item->getPathname();

            if ($item->isDir() && !$item->isLink()) {
                @rmdir($path);

                continue;
            }

            @unlink($path);
        }

        @rmdir($backups);
    }

    /**
     * @return list<string>
     */
    private function unselectedUiFiles(Profile $profile): array
    {
        return $profile === Profile::Tailwind
            ? self::BOOTSTRAP_ONLY_FILES
            : self::TAILWIND_ONLY_FILES;
    }

    private function installComposerDependencies(
        string $destination,
        string $composer,
        bool $installDevDependencies,
    ): ProcessResult {
        $command = [$composer, 'install', '--no-interaction', '--no-progress', '--prefer-dist'];

        if (!$installDevDependencies) {
            $command[] = '--no-dev';
        }

        $result = $this->runner->run($command, $destination);

        if (!$result->successful()) {
            throw new ProcessFailureException(sprintf(
                "PHP dependency installation failed (%s exited %d).\n%s\n"
                .'Project files were generated; fix the Composer error and run `composer install` in the project.',
                $result->describe(),
                $result->exitCode,
                $this->tail($result),
            ), $result->exitCode > 0 ? $result->exitCode : 1);
        }

        return $result;
    }

    private function installUiDependencies(string $destination, Toolchain $toolchain): ProcessResult
    {
        $command = [...$toolchain->command(), 'install'];
        $result = $this->runner->run($command, $destination);

        if (!$result->successful()) {
            throw new ProcessFailureException(sprintf(
                "UI dependency installation failed (%s exited %d).\n%s\n"
                .'Project files were generated; fix the package-manager error and run `npm install` in the project.',
                $result->describe(),
                $result->exitCode,
                $this->tail($result),
            ), $result->exitCode > 0 ? $result->exitCode : 1);
        }

        return $result;
    }

    private function configureEnvironment(string $destination, ProjectReport $report): void
    {
        $environment = $destination.'/.env';
        $example = $destination.'/.env.example';

        if (!is_file($environment)) {
            if (!is_file($example)) {
                $report->notes[] = '.env.example is missing; no .env file was created.';

                return;
            }

            if (!copy($example, $environment)) {
                throw new InstallerException('Unable to create .env from .env.example.');
            }

            $report->notes[] = 'created .env from .env.example';
        }

        $contents = file_get_contents($environment);

        if ($contents === false) {
            throw new InstallerException(sprintf('Unable to read [%s].', $environment));
        }

        if (preg_match('/^APP_KEY=(.*)$/m', $contents, $match) === 1 && trim($match[1]) !== '') {
            return;
        }

        $key = KeyGenerator::generate();

        if (preg_match('/^APP_KEY=.*$/m', $contents) === 1) {
            $contents = (string) preg_replace('/^APP_KEY=.*$/m', 'APP_KEY='.$key, $contents, 1);
        } else {
            $contents = rtrim($contents, "\r\n").PHP_EOL.'APP_KEY='.$key.PHP_EOL;
        }

        $this->writeAtomically($environment, $contents);
        $report->applicationKeyWritten = true;
    }

    private function writeAtomically(string $path, string $contents): void
    {
        $temporary = $path.'.tmp-'.bin2hex(random_bytes(4));
        $written = file_put_contents($temporary, $contents);

        if ($written === false || $written !== strlen($contents)) {
            @unlink($temporary);

            throw new InstallerException(sprintf('Unable to write [%s].', $path));
        }

        if (!rename($temporary, $path)) {
            @unlink($temporary);

            throw new InstallerException(sprintf('Unable to replace [%s].', $path));
        }
    }

    private function isEmptyDirectory(string $directory): bool
    {
        $entries = scandir($directory);

        if ($entries === false) {
            return false;
        }

        return count($entries) === 2;
    }

    private function effectivePath(string $path): string
    {
        $resolved = realpath($path);

        if ($resolved !== false) {
            return $resolved;
        }

        $parent = realpath(dirname($path));

        return $parent === false
            ? $path
            : rtrim($parent, DIRECTORY_SEPARATOR).DIRECTORY_SEPARATOR.basename($path);
    }

    private function absolutePath(string $path, string $base): string
    {
        if (str_contains($path, "\0")) {
            throw new InstallerException('Destination paths cannot contain NUL bytes.');
        }

        $path = trim($path);

        if ($path === '') {
            throw new InstallerException('Destination path cannot be empty.');
        }

        $isAbsolute = str_starts_with($path, DIRECTORY_SEPARATOR)
            || preg_match('/^[A-Za-z]:[\\\\\/]/', $path) === 1;

        if (!$isAbsolute) {
            $path = rtrim($base, DIRECTORY_SEPARATOR).DIRECTORY_SEPARATOR.$path;
        }

        $path = str_replace(['/', '\\'], DIRECTORY_SEPARATOR, $path);
        $prefix = '';

        if (preg_match('/^[A-Za-z]:/', $path) === 1) {
            $prefix = substr($path, 0, 2);
            $path = substr($path, 2);
        }

        $absolute = str_starts_with($path, DIRECTORY_SEPARATOR);
        $parts = [];

        foreach (explode(DIRECTORY_SEPARATOR, $path) as $part) {
            if ($part === '' || $part === '.') {
                continue;
            }

            if ($part === '..') {
                array_pop($parts);

                continue;
            }

            $parts[] = $part;
        }

        $normalized = $prefix
            .($absolute ? DIRECTORY_SEPARATOR : '')
            .implode(DIRECTORY_SEPARATOR, $parts);

        return $normalized === '' ? DIRECTORY_SEPARATOR : $normalized;
    }

    private function workingDirectory(): string
    {
        $directory = getcwd();

        return $directory === false ? __DIR__ : $directory;
    }

    private function tail(ProcessResult $result): string
    {
        $details = trim($result->stderr) !== '' ? trim($result->stderr) : trim($result->stdout);

        return strlen($details) <= 4000 ? $details : '...'.substr($details, -4000);
    }

    /**
     * @param (callable(string): void)|null $progress
     */
    private function notify(?callable $progress, string $message): void
    {
        if ($progress !== null) {
            $progress($message);
        }
    }
}
