<?php

declare(strict_types=1);

namespace Sahil\Theme;

use Sahil\Ui\Profile;

/**
 * Translates neutral theme tokens into framework-specific build-time files.
 *
 * Only valid, documented mappings are generated. Tailwind receives its
 * `@theme inline` variables; Bootstrap receives an optional Sass variable file
 * and a CSS-variable bridge for supported runtime tokens. Nothing here is
 * loaded by the framework at runtime.
 */
final class ThemeGenerator
{
    /**
     * Semantic aliases used by the generated sample layouts.
     *
     * @var array<string, string>
     */
    private const CSS_ALIASES = [
        '--sahil-primary' => '--sahil-color-primary',
        '--sahil-primary-dark' => '--sahil-color-primary-hover',
        '--sahil-text' => '--sahil-color-text',
        '--sahil-muted' => '--sahil-color-text-muted',
        '--sahil-border' => '--sahil-color-border',
        '--sahil-surface' => '--sahil-color-surface',
        '--sahil-surface-muted' => '--sahil-color-surface-muted',
        '--sahil-success' => '--sahil-color-success',
        '--sahil-success-bg' => '--sahil-color-success-surface',
        '--sahil-warning' => '--sahil-color-warning',
        '--sahil-warning-bg' => '--sahil-color-warning-surface',
        '--sahil-danger' => '--sahil-color-danger',
        '--sahil-danger-bg' => '--sahil-color-danger-surface',
    ];

    /**
     * Bootstrap frame breakpoints are a complete map. When a theme omits one,
     * keep Bootstrap's default rather than deleting the breakpoint.
     *
     * @var array<string, string>
     */
    private const BOOTSTRAP_BREAKPOINT_DEFAULTS = [
        'xs' => '0',
        'sm' => '576px',
        'md' => '768px',
        'lg' => '992px',
        'xl' => '1200px',
        'xxl' => '1400px',
    ];

    public function plan(ThemeTokens $tokens, Profile $profile): ThemePlan
    {
        $generated = [
            'resources/css/theme.tokens.generated.css' => $this->neutralCss($tokens),
        ];

        $user = [
            'resources/css/theme.overrides.css' => self::overridesCss(),
        ];

        $entries = [];

        if ($profile->includesTailwind()) {
            $generated['resources/css/theme.tailwind.generated.css'] = $this->tailwindCss($tokens);
            $entries['resources/css/tailwind.css'] = $this->entryBlock(tailwind: true, bootstrap: false);
        }

        if ($profile->includesBootstrap()) {
            $generated['resources/css/theme.bootstrap.generated.css'] = $this->bootstrapCss($tokens);
            $generated['resources/scss/_sahil-theme.generated.scss'] = $this->bootstrapScss($tokens);
            $user['resources/scss/_sahil-theme.overrides.scss'] = self::overridesScss();
            $entries['resources/css/bootstrap.css'] = $this->entryBlock(tailwind: false, bootstrap: true);
        }

        if ($profile === Profile::None) {
            $entries['resources/css/app.css'] = $this->entryBlock(tailwind: false, bootstrap: false);
        }

        ksort($generated);
        ksort($user);
        ksort($entries);

        return new ThemePlan($profile, $tokens, $generated, $user, $entries);
    }

    private function neutralCss(ThemeTokens $tokens): string
    {
        $lines = [
            '/*',
            ' * Generated by `bin/sahil ui:theme`. Do not edit this file.',
            ' * Theme: '.$tokens->name,
            ' * Source: theme/tokens.json (or the --source file passed to ui:theme).',
            ' * Overrides belong in resources/css/theme.overrides.css.',
            ' */',
            ':root {',
            '  color-scheme: light;',
        ];

        foreach ($tokens->colors as $name => $color) {
            $lines[] = sprintf('  --sahil-color-%s: %s;', $name, $color['light']);
        }

        if ($tokens->typography['font-sans'] !== null) {
            $lines[] = '  --sahil-font-sans: '.$tokens->typography['font-sans'].';';
        }

        if ($tokens->typography['font-mono'] !== null) {
            $lines[] = '  --sahil-font-mono: '.$tokens->typography['font-mono'].';';
        }

        foreach ($tokens->typography['sizes'] as $name => $value) {
            $lines[] = sprintf('  --sahil-text-%s: %s;', $name, $value);
        }

        foreach ($tokens->typography['line-heights'] as $name => $value) {
            $lines[] = sprintf('  --sahil-leading-%s: %s;', $name, $value);
        }

        foreach ($tokens->typography['weights'] as $name => $value) {
            $lines[] = sprintf('  --sahil-weight-%s: %s;', $name, $value);
        }

        foreach ($tokens->spacing as $name => $value) {
            $lines[] = sprintf('  --sahil-space-%s: %s;', $name, $value);
        }

        foreach ($tokens->borders['widths'] as $name => $value) {
            $lines[] = sprintf('  --sahil-border-width-%s: %s;', $name, $value);
        }

        $lines[] = '  --sahil-border-style: '.$tokens->borders['style'].';';

        foreach ($tokens->radii as $name => $value) {
            $lines[] = sprintf('  --sahil-radius-%s: %s;', $name, $value);
        }

        foreach ($tokens->breakpoints as $name => $value) {
            $lines[] = sprintf('  --sahil-breakpoint-%s: %s;', $name, $value);
        }

        foreach (self::CSS_ALIASES as $alias => $reference) {
            $colorName = substr($reference, strlen('--sahil-color-'));

            if (!isset($tokens->colors[$colorName])) {
                continue;
            }

            $lines[] = sprintf('  %s: var(%s);', $alias, $reference);
        }

        if ($tokens->typography['font-sans'] !== null) {
            $lines[] = '  --sahil-font: var(--sahil-font-sans);';
        }

        $lines[] = '}';
        $lines[] = '';
        $lines[] = '@media (prefers-color-scheme: dark) {';
        $lines[] = '  :root:not([data-theme="light"]):not([data-bs-theme="light"]) {';
        $lines[] = '    color-scheme: dark;';
        $lines = [...$lines, ...$this->darkColorLines($tokens, '    ')];
        $lines[] = '  }';
        $lines[] = '}';
        $lines[] = '';
        $lines[] = '[data-theme="dark"],';
        $lines[] = '[data-bs-theme="dark"] {';
        $lines[] = '  color-scheme: dark;';
        $lines = [...$lines, ...$this->darkColorLines($tokens, '  ')];
        $lines[] = '}';
        $lines[] = '';

        return implode("\n", $lines);
    }

    private function tailwindCss(ThemeTokens $tokens): string
    {
        $lines = [
            '/*',
            ' * Generated by `bin/sahil ui:theme` — Tailwind CSS v4 theme mapping.',
            ' * These are `@theme inline` variables so Tailwind utilities resolve the',
            ' * neutral CSS variables at runtime, including dark-mode overrides.',
            ' */',
            '@theme inline {',
        ];

        foreach (array_keys($tokens->colors) as $name) {
            $lines[] = sprintf('  --color-%s: var(--sahil-color-%s);', $name, $name);
        }

        if ($tokens->typography['font-sans'] !== null) {
            $lines[] = '  --font-sans: var(--sahil-font-sans);';
        }

        if ($tokens->typography['font-mono'] !== null) {
            $lines[] = '  --font-mono: var(--sahil-font-mono);';
        }

        foreach (array_keys($tokens->typography['sizes']) as $name) {
            $lines[] = sprintf('  --text-%s: var(--sahil-text-%s);', $name, $name);
        }

        foreach (array_keys($tokens->typography['line-heights']) as $name) {
            $lines[] = sprintf('  --leading-%s: var(--sahil-leading-%s);', $name, $name);
        }

        foreach (array_keys($tokens->typography['weights']) as $name) {
            $lines[] = sprintf('  --font-weight-%s: var(--sahil-weight-%s);', $name, $name);
        }

        if (isset($tokens->spacing['base'])) {
            $lines[] = '  --spacing: var(--sahil-space-base);';
        }

        foreach (array_keys($tokens->spacing) as $name) {
            if ($name === 'base') {
                continue;
            }

            $lines[] = sprintf('  --spacing-%s: var(--sahil-space-%s);', $name, $name);
        }

        foreach (array_keys($tokens->radii) as $name) {
            $lines[] = sprintf('  --radius-%s: var(--sahil-radius-%s);', $name, $name);
        }

        foreach (array_keys($tokens->borders['widths']) as $name) {
            $lines[] = sprintf('  --border-width-%s: var(--sahil-border-width-%s);', $name, $name);
        }

        foreach ($tokens->breakpoints as $name => $value) {
            // Media-query values cannot reference custom properties.
            $lines[] = sprintf('  --breakpoint-%s: %s;', $name, $value);
        }

        $lines[] = '}';
        $lines[] = '';

        return implode("\n", $lines);
    }

    private function bootstrapCss(ThemeTokens $tokens): string
    {
        $lines = [
            '/*',
            ' * Generated by `bin/sahil ui:theme` — Bootstrap 5 CSS-variable bridge.',
            ' * Bootstrap derives some values (notably RGB channel variables and',
            ' * contrast colors) at Sass compile time. Those variables are documented',
            ' * as unmapped; use the optional Sass file when they must change.',
            ' */',
            ':root {',
        ];

        $this->mappedVar($lines, '--bs-body-bg', '--sahil-color-surface', $tokens->colors, 'surface');
        $this->mappedVar($lines, '--bs-body-color', '--sahil-color-text', $tokens->colors, 'text');
        $this->mappedVar($lines, '--bs-secondary-color', '--sahil-color-text-muted', $tokens->colors, 'text-muted');
        $this->mappedVar($lines, '--bs-border-color', '--sahil-color-border', $tokens->colors, 'border');
        $this->mappedVar($lines, '--bs-primary', '--sahil-color-primary', $tokens->colors, 'primary');
        $this->mappedVar($lines, '--bs-link-color', '--sahil-color-primary', $tokens->colors, 'primary');
        $this->mappedVar($lines, '--bs-link-hover-color', '--sahil-color-primary-hover', $tokens->colors, 'primary-hover');

        if (isset($tokens->borders['widths']['thin'])) {
            $lines[] = '  --bs-border-width: var(--sahil-border-width-thin);';
        }

        $lines[] = '  --bs-border-style: '.$tokens->borders['style'].';';

        foreach (['sm', 'md', 'lg'] as $size) {
            if (isset($tokens->radii[$size])) {
                $suffix = $size === 'md' ? '' : '-'.$size;
                $lines[] = sprintf(
                    '  --bs-border-radius%s: var(--sahil-radius-%s);',
                    $suffix,
                    $size,
                );
            }
        }

        if ($tokens->typography['font-sans'] !== null) {
            $lines[] = '  --bs-body-font-family: var(--sahil-font-sans);';
        }

        if (isset($tokens->typography['sizes']['base'])) {
            $lines[] = '  --bs-body-font-size: var(--sahil-text-base);';
        }

        $lineHeight = $this->unitlessLineHeight($tokens);

        if ($lineHeight !== null) {
            $lines[] = '  --bs-body-line-height: var(--sahil-leading-'.$lineHeight.');';
        }

        $lines[] = '}';
        $lines[] = '';

        return implode("\n", $lines);
    }

    private function bootstrapScss(ThemeTokens $tokens): string
    {
        $lines = [
            '// Generated by `bin/sahil ui:theme` — optional Bootstrap Sass mapping.',
            '// This file is not imported by the precompiled Bootstrap profile. To use',
            '// it, compile Bootstrap from Sass and import this file before Bootstrap\'s',
            '// variables, or adapt the import order documented in docs/THEMING.md.',
        ];

        foreach (['primary', 'success', 'warning', 'danger'] as $name) {
            if (isset($tokens->colors[$name])) {
                $lines[] = sprintf('$%s: %s;', $name, $tokens->colors[$name]['light']);
            }
        }

        if (isset($tokens->colors['surface'])) {
            $lines[] = '$body-bg: '.$tokens->colors['surface']['light'].';';
        }

        if (isset($tokens->colors['text'])) {
            $lines[] = '$body-color: '.$tokens->colors['text']['light'].';';
        }

        if (isset($tokens->colors['text-muted'])) {
            $lines[] = '$body-secondary-color: '.$tokens->colors['text-muted']['light'].';';
        }

        if (isset($tokens->colors['border'])) {
            $lines[] = '$border-color: '.$tokens->colors['border']['light'].';';
        }

        if (isset($tokens->borders['widths']['thin'])) {
            $lines[] = '$border-width: '.$tokens->borders['widths']['thin'].';';
        }

        if (isset($tokens->radii['md'])) {
            $lines[] = '$border-radius: '.$tokens->radii['md'].';';
        }

        if (isset($tokens->radii['sm'])) {
            $lines[] = '$border-radius-sm: '.$tokens->radii['sm'].';';
        }

        if (isset($tokens->radii['lg'])) {
            $lines[] = '$border-radius-lg: '.$tokens->radii['lg'].';';
        }

        if ($tokens->typography['font-sans'] !== null) {
            $lines[] = '$font-family-sans-serif: '.$tokens->typography['font-sans'].';';
        }

        if ($tokens->typography['font-mono'] !== null) {
            $lines[] = '$font-family-monospace: '.$tokens->typography['font-mono'].';';
        }

        if (isset($tokens->typography['sizes']['base'])) {
            $lines[] = '$font-size-base: '.$tokens->typography['sizes']['base'].';';
        }

        $lineHeight = $this->unitlessLineHeight($tokens);

        if ($lineHeight !== null) {
            $lines[] = '$line-height-base: '.$tokens->typography['line-heights'][$lineHeight].';';
        }

        if (isset($tokens->spacing['md'])) {
            $lines[] = '$spacer: '.$tokens->spacing['md'].';';
        } elseif (isset($tokens->spacing['base'])) {
            $lines[] = '$spacer: '.$tokens->spacing['base'].';';
        }

        if ($tokens->breakpoints !== []) {
            $lines[] = '$grid-breakpoints: (';

            foreach (self::BOOTSTRAP_BREAKPOINT_DEFAULTS as $name => $default) {
                $lines[] = sprintf(
                    '  %s: %s,',
                    $name,
                    $tokens->breakpoints[$name] ?? $default,
                );
            }

            foreach ($tokens->breakpoints as $name => $value) {
                if (array_key_exists($name, self::BOOTSTRAP_BREAKPOINT_DEFAULTS)) {
                    continue;
                }

                $lines[] = sprintf('  %s: %s,', $name, $value);
            }

            $lines[] = ');';
        }

        $lines[] = '$enable-dark-mode: true;';
        $lines[] = '';

        return implode("\n", $lines);
    }

    private function entryBlock(bool $tailwind, bool $bootstrap): string
    {
        $imports = ['@import "./theme.tokens.generated.css";'];

        if ($tailwind) {
            $imports[] = '@import "./theme.tailwind.generated.css";';
        }

        if ($bootstrap) {
            $imports[] = '@import "./theme.bootstrap.generated.css";';
        }

        $imports[] = '@import "./theme.overrides.css";';

        return implode("\n", [
            '/* @sahil-theme:start */',
            ...$imports,
            '/* @sahil-theme:end */',
        ]);
    }

    /**
     * @param list<string>            $lines
     * @param array<string, array{light: string, dark: string}> $colors
     */
    private function mappedVar(
        array &$lines,
        string $bootstrapVariable,
        string $neutralVariable,
        array $colors,
        string $colorName,
    ): void {
        if (!isset($colors[$colorName])) {
            return;
        }

        $lines[] = sprintf('  %s: var(%s);', $bootstrapVariable, $neutralVariable);
    }

    /**
     * @return list<string>
     */
    private function darkColorLines(ThemeTokens $tokens, string $indent): array
    {
        $lines = [];

        foreach ($tokens->colors as $name => $color) {
            $lines[] = sprintf('%s--sahil-color-%s: %s;', $indent, $name, $color['dark']);
        }

        return $lines;
    }

    private function unitlessLineHeight(ThemeTokens $tokens): ?string
    {
        foreach (['normal', 'base', 'relaxed'] as $name) {
            if (
                isset($tokens->typography['line-heights'][$name])
                && preg_match('/^[-+]?(?:\d*\.)?\d+$/', $tokens->typography['line-heights'][$name]) === 1
            ) {
                return $name;
            }
        }

        foreach ($tokens->typography['line-heights'] as $name => $value) {
            if (preg_match('/^[-+]?(?:\d*\.)?\d+$/', $value) === 1) {
                return $name;
            }
        }

        return null;
    }

    private static function overridesCss(): string
    {
        return <<<'CSS'
            /*
             * Application theme overrides.
             *
             * This file is imported after the generated theme files and is never
             * replaced by `ui:theme`. Override neutral tokens here when you want a
             * small change without editing theme/tokens.json:
             *
             * :root {
             *   --sahil-color-primary: #0f766e;
             * }
             *
             * [data-theme="dark"] {
             *   --sahil-color-primary: #2dd4bf;
             * }
             *
             * To change the whole theme, edit theme/tokens.json and run
             * `bin/sahil ui:theme`.
             */
            CSS;
    }

    private static function overridesScss(): string
    {
        return <<<'SCSS'
            // Application Bootstrap Sass overrides.
            //
            // This file is never replaced by `ui:theme`. Import it after
            // _sahil-theme.generated.scss when compiling Bootstrap from Sass.
            //
            // $primary: #0f766e;
            SCSS;
    }
}
